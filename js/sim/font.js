  // 글자 → 25칸 밝기 배열 (0 또는 9)
  function glyph(ch) {
    const g = G[ch] || G['?'];
    return g.replace(/ /g, '').split('').map(c => (c === '#' ? 9 : 0));
  }

  // 글자 → 열(column) 배열. 각 열은 5행 밝기 배열. 비고정폭이면 좌우 빈 열 제거
  function columns(ch, monospace) {
    const px = glyph(ch);
    let cols = [];
    for (let x = 0; x < 5; x++) cols.push([0, 1, 2, 3, 4].map(y => px[y * 5 + x]));
    if (!monospace) {
      if (ch === ' ') return cols.slice(0, 3);
      const lit = c => c.some(v => v);
      while (cols.length && !lit(cols[0])) cols.shift();
      while (cols.length && !lit(cols[cols.length - 1])) cols.pop();
      if (!cols.length) cols = [[0, 0, 0, 0, 0]];
    }
    return cols;
  }

  // 스크롤용 전체 열 배열 (글자 사이 1열 간격)
  function textColumns(text, monospace) {
    const out = [];
    for (const ch of String(text)) {
      for (const c of columns(ch, monospace)) out.push(c);
      out.push([0, 0, 0, 0, 0]);
    }
    return out;
  }

  window.MBFont = { glyph, columns, textColumns };
